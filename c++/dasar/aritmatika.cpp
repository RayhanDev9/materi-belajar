#include <iostream>

using namespace std;

int main() {
    int a = 2;
    int b = 6;

    cout << "=== OPERASI ARITMATIKA ===" << endl;
    cout << "Nilai a = " << a << ", Nilai b = " << b << "\n" << endl;

    cout << a << " + " << b << " = " << a + b << endl;
    cout << a << " - " << b << " = " << a - b << endl;
    cout << a << " * " << b << " = " << a * b << endl;
    cout << a << " / " << b << " = " << a / b << endl;
    cout << a << " % " << b << " = " << a % b << endl;

    return 0;
}